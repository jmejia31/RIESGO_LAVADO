-- Ciclo de vida administrativo de familias de formularios.
-- Preparado para ejecución autorizada; esta intervención no ejecuta DDL/DML en producción.
-- Idempotente y fail-closed: no elimina ni transforma datos históricos.
DECLARE
  l_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO l_exists FROM USER_TAB_COLUMNS
   WHERE TABLE_NAME = 'RL_MR_FAMILIAS_FORMULARIO' AND COLUMN_NAME = 'FAM_ARCHIVADA';
  IF l_exists = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE RL_MR_FAMILIAS_FORMULARIO ADD (FAM_ARCHIVADA NUMBER(1) DEFAULT 0 NOT NULL)';
  END IF;
  SELECT COUNT(*) INTO l_exists FROM USER_TAB_COLUMNS
   WHERE TABLE_NAME = 'RL_MR_FAMILIAS_FORMULARIO' AND COLUMN_NAME = 'FAM_FECHA_ARCHIVADO';
  IF l_exists = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE RL_MR_FAMILIAS_FORMULARIO ADD (FAM_FECHA_ARCHIVADO DATE)';
  END IF;
  SELECT COUNT(*) INTO l_exists FROM USER_TAB_COLUMNS
   WHERE TABLE_NAME = 'RL_MR_FAMILIAS_FORMULARIO' AND COLUMN_NAME = 'FAM_USR_ARCHIVADO';
  IF l_exists = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE RL_MR_FAMILIAS_FORMULARIO ADD (FAM_USR_ARCHIVADO NUMBER(15))';
  END IF;
  SELECT COUNT(*) INTO l_exists FROM USER_TAB_COLUMNS
   WHERE TABLE_NAME = 'RL_MR_FAMILIAS_FORMULARIO' AND COLUMN_NAME = 'FAM_MOTIVO_ARCHIVADO';
  IF l_exists = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE RL_MR_FAMILIAS_FORMULARIO ADD (FAM_MOTIVO_ARCHIVADO VARCHAR2(500))';
  END IF;
  SELECT COUNT(*) INTO l_exists FROM USER_CONSTRAINTS
   WHERE TABLE_NAME = 'RL_MR_FAMILIAS_FORMULARIO' AND CONSTRAINT_NAME = 'CK_RL_MR_FAM_ARCHIVADA';
  IF l_exists = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE RL_MR_FAMILIAS_FORMULARIO ADD CONSTRAINT CK_RL_MR_FAM_ARCHIVADA CHECK (FAM_ARCHIVADA IN (0,1))';
  END IF;
  DBMS_OUTPUT.PUT_LINE('FAMILY_ARCHIVE_DDL=READY');
END;
/
