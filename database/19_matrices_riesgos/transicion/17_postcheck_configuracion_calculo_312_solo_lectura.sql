PROMPT DUPLICADOS_Y_CONTRATOS
SELECT 'DUPLICATE_FORMULA_CODES' AS METRICA, NVL(SUM(CASE WHEN C > 1 THEN 1 ELSE 0 END),0) AS VALOR FROM (SELECT FOR_CODIGO,COUNT(*) C FROM RL_MR_FORMULAS GROUP BY FOR_CODIGO)
UNION ALL SELECT 'DUPLICATE_FUNCTION_CODES', NVL(SUM(CASE WHEN C > 1 THEN 1 ELSE 0 END),0) FROM (SELECT FUN_CODIGO,COUNT(*) C FROM RL_MR_FUNCIONES GROUP BY FUN_CODIGO)
UNION ALL SELECT 'DUPLICATE_PARAMETER_CODES', NVL(SUM(CASE WHEN C > 1 THEN 1 ELSE 0 END),0) FROM (SELECT PAC_CODIGO,COUNT(*) C FROM RL_MR_PARAMETROS_CALCULO GROUP BY PAC_CODIGO)
UNION ALL SELECT 'DUPLICATE_FORMULA_VERSIONS', NVL(SUM(CASE WHEN C > 1 THEN 1 ELSE 0 END),0) FROM (SELECT FOV_FORMULA_ID,FOV_VERSION,COUNT(*) C FROM RL_MR_FORMULA_VERSIONES GROUP BY FOV_FORMULA_ID,FOV_VERSION)
UNION ALL SELECT 'DUPLICATE_FUNCTION_VERSIONS', NVL(SUM(CASE WHEN C > 1 THEN 1 ELSE 0 END),0) FROM (SELECT FUV_FUNCION_ID,FUV_VERSION,COUNT(*) C FROM RL_MR_FUNCION_VERSIONES GROUP BY FUV_FUNCION_ID,FUV_VERSION)
UNION ALL SELECT 'DUPLICATE_PARAMETER_VERSIONS', NVL(SUM(CASE WHEN C > 1 THEN 1 ELSE 0 END),0) FROM (SELECT PAV_PARAMETRO_ID,PAV_VERSION,COUNT(*) C FROM RL_MR_PARAMETRO_VERSIONES GROUP BY PAV_PARAMETRO_ID,PAV_VERSION)
UNION ALL SELECT 'INVALID_NATIVE_COMPOSITE_CONTRACTS', COUNT(*) FROM RL_MR_FUNCION_VERSIONES WHERE (FUV_TIPO='NATIVE' AND (FUV_HANDLER_KEY IS NULL OR FUV_DEFINICION_DSL IS NOT NULL)) OR (FUV_TIPO='COMPOSITE' AND (FUV_HANDLER_KEY IS NOT NULL OR FUV_DEFINICION_DSL IS NULL))
UNION ALL SELECT 'INVALID_HASH_FORMATS', COUNT(*) FROM RL_MR_FORMULA_VERSIONES WHERE NOT REGEXP_LIKE(FOV_HASH,'^[0-9A-Fa-f]{64}$')
UNION ALL SELECT 'INVALID_HASH_FORMATS', COUNT(*) FROM RL_MR_FUNCION_VERSIONES WHERE NOT REGEXP_LIKE(FUV_HASH,'^[0-9A-Fa-f]{64}$')
UNION ALL SELECT 'INVALID_HASH_FORMATS', COUNT(*) FROM RL_MR_PARAMETRO_VERSIONES WHERE NOT REGEXP_LIKE(PAV_HASH,'^[0-9A-Fa-f]{64}$');

