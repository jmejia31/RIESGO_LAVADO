WHENEVER SQLERROR EXIT SQL.SQLCODE
SET SERVEROUTPUT ON SIZE UNLIMITED
DECLARE v_rows NUMBER:=0;
BEGIN
  UPDATE RL_MR_VERSIONES_FORMULARIO SET VER_FECHA_FIN=TO_DATE('2026-08-13 09:38:44','YYYY-MM-DD HH24:MI:SS') WHERE VER_ID=1 AND VER_FAMILIA_ID=2 AND VER_VERSION=1 AND VER_FECHA_FIN=TO_DATE('2026-08-12 11:12:44','YYYY-MM-DD HH24:MI:SS'); v_rows:=v_rows+SQL%ROWCOUNT;
  UPDATE RL_MR_VERSIONES_FORMULARIO SET VER_FECHA_FIN=TO_DATE('2026-08-20 09:47:55','YYYY-MM-DD HH24:MI:SS') WHERE VER_ID=17 AND VER_FAMILIA_ID=2 AND VER_VERSION=5 AND VER_FECHA_FIN=TO_DATE('2026-08-19 15:12:19','YYYY-MM-DD HH24:MI:SS'); v_rows:=v_rows+SQL%ROWCOUNT;
  UPDATE RL_MR_VERSIONES_FORMULARIO SET VER_FECHA_FIN=TO_DATE('2026-08-20 15:01:09','YYYY-MM-DD HH24:MI:SS') WHERE VER_ID=25 AND VER_FAMILIA_ID=2 AND VER_VERSION=7 AND VER_FECHA_FIN=TO_DATE('2026-08-20 14:28:03','YYYY-MM-DD HH24:MI:SS'); v_rows:=v_rows+SQL%ROWCOUNT;
  IF v_rows<>3 THEN ROLLBACK; RAISE_APPLICATION_ERROR(-20930,'Rollback no afecto exactamente tres filas.'); END IF;
  COMMIT; DBMS_OUTPUT.PUT_LINE('ROLLBACK_ROWS=3');
END;
/
EXIT
