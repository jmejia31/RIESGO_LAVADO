PROMPT === DB03_Q09 AUDITORIA PAGINADA CON FILTROS EXACTOS Y FECHA ===
EXPLAIN PLAN SET STATEMENT_ID = 'D3Q09_&DB03_RUN_ID' FOR
SELECT * FROM (
    SELECT a.*, ROWNUM rnum FROM (
        SELECT AUD_ID, AUD_TABLA, AUD_REGISTRO_ID, AUD_ACCION,
               AUD_DATOS_ANT, AUD_DATOS_NVO, AUD_USR_ID,
               NVL((SELECT USR_NOMBRE || ' ' || USR_APELLIDO
                      FROM RL_USUARIOS
                     WHERE USR_ID = AUD_USR_ID), AUD_USR_EMAIL) AS AUD_USR_EMAIL,
               AUD_IP, AUD_FECHA, AUD_MODULO
          FROM RL_AUDITORIA
         WHERE AUD_ACCION = :accionFilter
           AND AUD_MODULO = :moduloFilter
           AND AUD_TABLA = :tablaFilter
           AND AUD_FECHA >= :fechaInicioFilter
           AND AUD_FECHA <= :fechaFinFilter
         ORDER BY AUD_FECHA DESC, AUD_ID DESC
    ) a WHERE ROWNUM <= :maxRow
) WHERE rnum > :minRow;
SELECT PLAN_TABLE_OUTPUT FROM TABLE(DBMS_XPLAN.DISPLAY('PLAN_TABLE', 'D3Q09_&DB03_RUN_ID', 'TYPICAL +ALIAS +PREDICATE'));

PROMPT === DB03_Q10 AUDITORIA PAGINADA CON BUSQUEDA DE SUBCADENA ===
EXPLAIN PLAN SET STATEMENT_ID = 'D3Q10_&DB03_RUN_ID' FOR
SELECT * FROM (
    SELECT a.*, ROWNUM rnum FROM (
        SELECT AUD_ID, AUD_TABLA, AUD_REGISTRO_ID, AUD_ACCION,
               AUD_DATOS_ANT, AUD_DATOS_NVO, AUD_USR_ID,
               NVL((SELECT USR_NOMBRE || ' ' || USR_APELLIDO
                      FROM RL_USUARIOS
                     WHERE USR_ID = AUD_USR_ID), AUD_USR_EMAIL) AS AUD_USR_EMAIL,
               AUD_IP, AUD_FECHA, AUD_MODULO
          FROM RL_AUDITORIA
         WHERE (LOWER(AUD_USR_EMAIL) LIKE :buscarFilter
             OR LOWER(NVL(AUD_USR_EMAIL,
                    (SELECT USR_EMAIL FROM RL_USUARIOS WHERE USR_ID = AUD_USR_ID))) LIKE :buscarFilter
             OR LOWER(AUD_TABLA) LIKE :buscarFilter
             OR LOWER(AUD_IP) LIKE :buscarFilter
             OR LOWER(AUD_REGISTRO_ID) LIKE :buscarFilter)
         ORDER BY AUD_FECHA DESC, AUD_ID DESC
    ) a WHERE ROWNUM <= :maxRow
) WHERE rnum > :minRow;
SELECT PLAN_TABLE_OUTPUT FROM TABLE(DBMS_XPLAN.DISPLAY('PLAN_TABLE', 'D3Q10_&DB03_RUN_ID', 'TYPICAL +ALIAS +PREDICATE'));

