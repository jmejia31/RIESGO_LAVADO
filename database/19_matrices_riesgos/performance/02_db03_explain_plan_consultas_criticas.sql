PROMPT === DB03_Q02 PAGINACION DE EVALUACIONES SIN FILTROS OPCIONALES ===
EXPLAIN PLAN SET STATEMENT_ID = 'D3Q02_&DB03_RUN_ID' FOR
SELECT *
  FROM (
        SELECT q.*, ROWNUM NUMERO_FILA
          FROM (
                SELECT e.EVA_ID,
                       e.EVA_RIESGO_ID,
                       e.EVA_VERSION_ID,
                       NVL(f.FLU_ESTADO, 'BORRADOR') FLU_ESTADO,
                       e.EVA_DATOS_JSON,
                       e.EVA_CALCULOS_JSON,
                       p.PROY_VRI,
                       CAST(NULL AS NUMBER) VALOR_RESERVADO,
                       p.PROY_VRR,
                       e.EVA_FECHA_REGISTRO,
                       e.EVA_USR_REGISTRO,
                       e.EVA_VERSION_ROW,
                       e.EVA_ACTIVO
                  FROM RL_MR_EVALUACIONES_RIESGO e
                  LEFT JOIN RL_MR_PROYECCIONES_EVALUACION p
                    ON p.PROY_EVALUACION_ID = e.EVA_ID
                  LEFT JOIN (
                        SELECT FLU_EVALUACION_ID, FLU_ESTADO
                          FROM (
                                SELECT FLU_EVALUACION_ID,
                                       FLU_ESTADO,
                                       ROW_NUMBER() OVER (
                                           PARTITION BY FLU_EVALUACION_ID
                                           ORDER BY FLU_FECHA DESC, FLU_ID DESC
                                       ) RN
                                  FROM RL_MR_FLUJOS_EVALUACION
                               )
                         WHERE RN = 1
                  ) f
                    ON f.FLU_EVALUACION_ID = e.EVA_ID
                 WHERE e.EVA_ACTIVO = 1
                 ORDER BY e.EVA_FECHA_REGISTRO DESC, e.EVA_ID DESC
               ) q
         WHERE ROWNUM <= :filaFinal
       )
 WHERE NUMERO_FILA > :filaInicial;
SELECT PLAN_TABLE_OUTPUT FROM TABLE(DBMS_XPLAN.DISPLAY('PLAN_TABLE', 'D3Q02_&DB03_RUN_ID', 'TYPICAL +ALIAS +PREDICATE'));

