-- B06 DDL controlado: parametrización del color de encabezado de reportes.
-- No se ejecuta desde los maestros automáticos y no se ejecuta desde Codex.
-- Requiere respaldo validado, ventana DBA y aprobación operativa.
SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
  v_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_exists FROM USER_TABLES WHERE TABLE_NAME = 'RL_CONFIG_SISTEMA';
  IF v_exists = 0 THEN
    RAISE_APPLICATION_ERROR(-20062, 'RL_CONFIG_SISTEMA no existe.');
  END IF;

  SELECT COUNT(*) INTO v_exists FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'RL_CONFIG_SISTEMA' AND COLUMN_NAME = 'SFS_COLOR_ENCABEZADO_REPORTES';
  IF v_exists = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE RL_CONFIG_SISTEMA ADD (SFS_COLOR_ENCABEZADO_REPORTES VARCHAR2(7 CHAR))';
    EXECUTE IMMEDIATE 'COMMENT ON COLUMN RL_CONFIG_SISTEMA.SFS_COLOR_ENCABEZADO_REPORTES IS ''Color hexadecimal del encabezado institucional de PDF, Excel y previews.''';
  END IF;

  EXECUTE IMMEDIATE 'UPDATE RL_CONFIG_SISTEMA SET SFS_COLOR_ENCABEZADO_REPORTES = NVL(SFS_COLOR_ENCABEZADO_REPORTES, ''#123B63'') WHERE SFS_ID = 1';
  COMMIT;
  DBMS_OUTPUT.PUT_LINE('B06_DYNAMIC_BRANDING_DDL=PASS');
END;
/
EXIT
