SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
  v_columns NUMBER;
  v_value VARCHAR2(7);
BEGIN
  SELECT COUNT(*) INTO v_columns FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'RL_CONFIG_SISTEMA' AND COLUMN_NAME = 'SFS_COLOR_ENCABEZADO_REPORTES';
  IF v_columns <> 1 THEN RAISE_APPLICATION_ERROR(-20063, 'Columna B06 ausente.'); END IF;
  SELECT SFS_COLOR_ENCABEZADO_REPORTES INTO v_value FROM RL_CONFIG_SISTEMA WHERE SFS_ID = 1;
  IF NOT REGEXP_LIKE(v_value, '^#[0-9A-Fa-f]{6}$') THEN
    RAISE_APPLICATION_ERROR(-20064, 'El valor B06 no cumple formato hexadecimal.');
  END IF;
  DBMS_OUTPUT.PUT_LINE('B06_POSTCHECK=PASS');
  DBMS_OUTPUT.PUT_LINE('SFS_COLOR_ENCABEZADO_REPORTES=' || v_value);
END;
/
EXIT
