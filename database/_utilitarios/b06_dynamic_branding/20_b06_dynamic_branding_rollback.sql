-- B06 ROLLBACK CONTROLADO. Ejecutar solo con aprobación DBA y confirmación de que
-- la columna fue creada exclusivamente por 20_b06_dynamic_branding.sql.
SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
  v_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_exists FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'RL_CONFIG_SISTEMA' AND COLUMN_NAME = 'SFS_COLOR_ENCABEZADO_REPORTES';
  IF v_exists = 1 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE RL_CONFIG_SISTEMA DROP COLUMN SFS_COLOR_ENCABEZADO_REPORTES';
  END IF;
  DBMS_OUTPUT.PUT_LINE('B06_ROLLBACK=PASS');
END;
/
EXIT
