-- B06 PRECHECK (solo lectura). No ejecutar contra Oracle institucional sin ventana DBA.
SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
  v_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_exists FROM USER_TABLES WHERE TABLE_NAME = 'RL_CONFIG_SISTEMA';
  IF v_exists = 0 THEN
    RAISE_APPLICATION_ERROR(-20061, 'RL_CONFIG_SISTEMA no existe.');
  END IF;
  DBMS_OUTPUT.PUT_LINE('B06_PRECHECK=PASS');
  SELECT COUNT(*) INTO v_exists FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'RL_CONFIG_SISTEMA' AND COLUMN_NAME = 'SFS_COLOR_ENCABEZADO_REPORTES';
  DBMS_OUTPUT.PUT_LINE('SFS_COLOR_ENCABEZADO_REPORTES=' || CASE WHEN v_exists = 1 THEN 'PRESENTE' ELSE 'PENDIENTE' END);
END;
/
EXIT
