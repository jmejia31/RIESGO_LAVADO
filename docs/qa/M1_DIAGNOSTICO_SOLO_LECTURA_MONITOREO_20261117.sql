-- R03 | Distribucion TIPO_PERSONA x TIPO_CALIFICACION_ID.
SELECT NVL(TIPO_PERSONA,'(NULL)') TIPO_PERSONA, TIPO_CALIFICACION_ID, COUNT(*) FILAS,
