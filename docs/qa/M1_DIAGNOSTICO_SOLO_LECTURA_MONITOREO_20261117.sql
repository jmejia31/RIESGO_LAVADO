-- Q02 | Inventario de columnas para identificar claves reales (sin valores personales).
SELECT OWNER, TABLE_NAME, COLUMN_NAME, DATA_TYPE, NULLABLE
FROM ALL_TAB_COLUMNS
WHERE OWNER = 'DNP_IHSS'
  AND TABLE_NAME IN (
      'REPORTE_COINCIDENCIAS', 'SOCIOS', 'REPRESENTANTES',
      'V_SOCIOS_REPRESENTANTES', 'V_EMPLEADOS_IHSS_PLANILLAS'
  )
  AND (
      COLUMN_NAME LIKE '%ID%'
      OR COLUMN_NAME LIKE '%PERIODO%'
      OR COLUMN_NAME LIKE '%DOCUMENT%'
      OR COLUMN_NAME LIKE '%PATRON%'
      OR COLUMN_NAME LIKE '%EMPRESA%'
      OR COLUMN_NAME LIKE '%FECHA%'
      OR COLUMN_NAME LIKE '%LISTA%'
  )
ORDER BY TABLE_NAME, COLUMN_NAME;

-- Q03 | Claves declaradas de las tablas de origen. Las vistas pueden no tener constraints.
SELECT C.TABLE_NAME, C.CONSTRAINT_TYPE, C.CONSTRAINT_NAME,
       CC.COLUMN_NAME, CC.POSITION
FROM ALL_CONSTRAINTS C
JOIN ALL_CONS_COLUMNS CC
  ON C.OWNER = CC.OWNER
 AND C.CONSTRAINT_NAME = CC.CONSTRAINT_NAME
WHERE C.OWNER = 'DNP_IHSS'
  AND C.TABLE_NAME IN ('REPORTE_COINCIDENCIAS', 'SOCIOS', 'REPRESENTANTES')
  AND C.CONSTRAINT_TYPE IN ('P','U')
ORDER BY C.TABLE_NAME, C.CONSTRAINT_NAME, CC.POSITION;

-- Q04 | Cardinalidad natural: filas originales frente a agrupaciones de la consulta actual.
WITH R AS (
    SELECT DNI, LISTA_CONCIDENCIA, NOMBRE, FECHA_CALIFICO
    FROM DNP_IHSS.REPORTE_COINCIDENCIAS
    WHERE TIPO_CALIFICACION_ID = 1
)
SELECT 'R_TIPO_1_FILAS_ORIGEN' AS METRICA, COUNT(*) AS VALOR FROM R
UNION ALL
SELECT 'R_TIPO_1_GRUPOS_DNI_LISTA', COUNT(*)
FROM (SELECT DNI, LISTA_CONCIDENCIA FROM R GROUP BY DNI, LISTA_CONCIDENCIA)
UNION ALL
SELECT 'R_TIPO_1_GRUPOS_DNI_LISTA_NOMBRE', COUNT(*)
FROM (
    SELECT DNI, LISTA_CONCIDENCIA,
           TRIM(REGEXP_REPLACE(NOMBRE, '[[:space:]]+', ' ')) AS NOMBRE_NORMALIZADO
    FROM R
    GROUP BY DNI, LISTA_CONCIDENCIA,
             TRIM(REGEXP_REPLACE(NOMBRE, '[[:space:]]+', ' '))
)
UNION ALL
SELECT 'R_TIPO_1_SIN_FECHA_CALIFICO', COUNT(*)
FROM R WHERE FECHA_CALIFICO IS NULL
UNION ALL
SELECT 'R_TIPO_1_MARCADOR_NA3', COUNT(*)
FROM R WHERE UPPER(TRIM(DNI)) = 'N/A(3)'
UNION ALL
SELECT 'R_TIPO_1_SIN_IDENTIFICACION', COUNT(*)
FROM R WHERE DNI IS NULL OR UPPER(TRIM(DNI)) LIKE 'N/A%'
 OR UPPER(TRIM(DNI)) IN ('NULL','VACIO','VACÍO','SIN IDENTIFICACION','SIN IDENTIFICACIÓN')
ORDER BY METRICA;

-- Q05 | Cuantos grupos de DNI/lista mezclan filas/nombres; solo agregados, sin DNI.
WITH G AS (
    SELECT DNI, LISTA_CONCIDENCIA, COUNT(*) AS FILAS,
           COUNT(DISTINCT TRIM(REGEXP_REPLACE(NOMBRE, '[[:space:]]+', ' '))) AS NOMBRES
    FROM DNP_IHSS.REPORTE_COINCIDENCIAS
    WHERE TIPO_CALIFICACION_ID = 1
    GROUP BY DNI, LISTA_CONCIDENCIA
)
SELECT COUNT(*) AS GRUPOS_DNI_LISTA,
       NVL(SUM(CASE WHEN FILAS > 1 THEN 1 ELSE 0 END),0) AS GRUPOS_CON_REPETICIONES,
       NVL(SUM(FILAS-1),0) AS FILAS_AGRUPADAS,
       NVL(SUM(CASE WHEN NOMBRES > 1 THEN 1 ELSE 0 END),0) AS GRUPOS_CON_NOMBRES_DIFERENTES
FROM G;

-- Q06 | Cobertura del detalle natural: cuantas claves del reporte no aparecen en la vista.
-- No implica que un DNI comun autorice atribuir TODAS las empresas a un mismo sujeto.
WITH R AS (
    SELECT DNI
    FROM DNP_IHSS.REPORTE_COINCIDENCIAS
    WHERE TIPO_CALIFICACION_ID = 1 AND DNI IS NOT NULL
    GROUP BY DNI
),
S AS (
    SELECT NUMERO_IDENTIFICACION
    FROM DNP_IHSS.V_SOCIOS_REPRESENTANTES
    WHERE NUMERO_IDENTIFICACION IS NOT NULL
    GROUP BY NUMERO_IDENTIFICACION
)
SELECT COUNT(*) AS DOCUMENTOS_EN_REPORTE,
       NVL(SUM(CASE WHEN S.NUMERO_IDENTIFICACION IS NULL THEN 1 ELSE 0 END),0) AS DOCUMENTOS_SIN_VISTA_DETALLE,
       NVL(SUM(CASE WHEN S.NUMERO_IDENTIFICACION IS NOT NULL THEN 1 ELSE 0 END),0) AS DOCUMENTOS_CON_VISTA_DETALLE
FROM R
LEFT JOIN S ON S.NUMERO_IDENTIFICACION = R.DNI;

-- Q07 | Relaciones fuente persona-empresa candidatas de los DNI presentes en el reporte.
-- Es cardinalidad de la fuente, NO una asociacion individual ya verificada.
WITH R AS (
    SELECT DNI
    FROM DNP_IHSS.REPORTE_COINCIDENCIAS
    WHERE TIPO_CALIFICACION_ID = 1 AND DNI IS NOT NULL
    GROUP BY DNI
)
SELECT COUNT(*) AS COMBINACIONES_FUENTE_DISTINTAS
FROM (
    SELECT S.NUMERO_IDENTIFICACION, S.NUMERO_PATRONAL,
           S.NOMBRE_EMPRESA, S.TIPO_CONDICION_ACTUA_DESC
    FROM DNP_IHSS.V_SOCIOS_REPRESENTANTES S
    WHERE EXISTS (SELECT 1 FROM R WHERE R.DNI = S.NUMERO_IDENTIFICACION)
    GROUP BY S.NUMERO_IDENTIFICACION, S.NUMERO_PATRONAL,
             S.NOMBRE_EMPRESA, S.TIPO_CONDICION_ACTUA_DESC
);

-- Q08 | Registros manuales activos: se distinguen del reporte de origen.
SELECT LSP_TIPO_POSITIVO_ID AS TIPO,
       COUNT(*) AS REGISTROS_MANUALES_O_POSITIVOS_ACTIVOS,
       NVL(SUM(CASE WHEN LSP_MOTIVO_INGRESO IS NULL THEN 1 ELSE 0 END),0) AS SIN_MOTIVO
FROM RL_LISTA_POSITIVOS
WHERE LSP_TIPO_POSITIVO_ID IN (2,3)
  AND LSP_ESTADO_REGISTRO = 1
GROUP BY LSP_TIPO_POSITIVO_ID
ORDER BY LSP_TIPO_POSITIVO_ID;

-- Q09 | Las fechas de calificacion no son equivalentes a la clasificacion.
SELECT TIPO_CALIFICACION_ID AS CALIFICACION,
       COUNT(*) AS FILAS,
       NVL(SUM(CASE WHEN FECHA_CALIFICO IS NULL THEN 1 ELSE 0 END),0) AS SIN_FECHA_CALIFICO,
       NVL(SUM(CASE WHEN FECHA_ENCONTRO IS NULL THEN 1 ELSE 0 END),0) AS SIN_FECHA_ENCONTRO
FROM DNP_IHSS.REPORTE_COINCIDENCIAS
GROUP BY TIPO_CALIFICACION_ID
ORDER BY TIPO_CALIFICACION_ID;

-- Q10 | Inventario institucional de empleado/patrono segun la vista usada por otros endpoints.
SELECT CASE WHEN TIPO_PERSONA LIKE '%IHSS' THEN 'EMPLEADO_IHSS'
            ELSE 'OTRO_TIPO_PERSONA' END AS CATEGORIA_FUENTE,
       COUNT(*) AS FILAS_ORIGEN
FROM DNP_IHSS.V_REPORTE_COINCIDENCIA
GROUP BY CASE WHEN TIPO_PERSONA LIKE '%IHSS' THEN 'EMPLEADO_IHSS'
              ELSE 'OTRO_TIPO_PERSONA' END
ORDER BY CATEGORIA_FUENTE;

-- Q11 | Vista de empleados SOLO para DNI con coincidencia TIPO=1.
-- Ejecutar con control del DBA si la vista historica es pesada.
WITH R AS (
    SELECT DNI FROM DNP_IHSS.REPORTE_COINCIDENCIAS
    WHERE TIPO_CALIFICACION_ID = 1 AND DNI IS NOT NULL
    GROUP BY DNI
),
P AS (
    SELECT E.IDENTIDAD, E.PERIODO
    FROM DNP_IHSS.V_EMPLEADOS_IHSS_PLANILLAS E
    WHERE EXISTS (SELECT 1 FROM R WHERE R.DNI = E.IDENTIDAD)
)
SELECT COUNT(*) AS FILAS_PLANILLA_CON_COINCIDENCIA,
       COUNT(DISTINCT IDENTIDAD) AS IDENTIDADES_CON_COINCIDENCIA,
       COUNT(DISTINCT PERIODO) AS PERIODOS_DISTINTOS,
       NVL(SUM(CASE WHEN PERIODO IS NULL THEN 1 ELSE 0 END),0) AS FILAS_SIN_PERIODO
FROM P;

-- Q12 | Estimar la multiplicacion por JOIN a traves de multiples planillas.
-- No sustituye comprobar las relaciones historicas fila por fila.
WITH R AS (
    SELECT DNI, LISTA_CONCIDENCIA, COUNT(*) AS FILAS_REPORTE
    FROM DNP_IHSS.REPORTE_COINCIDENCIAS
    WHERE TIPO_CALIFICACION_ID = 1 AND DNI IS NOT NULL
    GROUP BY DNI, LISTA_CONCIDENCIA
),
E AS (
    SELECT IDENTIDAD, COUNT(*) AS FILAS_PLANILLA
    FROM DNP_IHSS.V_EMPLEADOS_IHSS_PLANILLAS
    WHERE EXISTS (SELECT 1 FROM R WHERE R.DNI = IDENTIDAD)
    GROUP BY IDENTIDAD
)
SELECT COUNT(*) AS GRUPOS_DNI_LISTA_MATCH,
       NVL(SUM(R.FILAS_REPORTE),0) AS FILAS_REPORTE_VINCULADAS,
       NVL(SUM(R.FILAS_REPORTE*E.FILAS_PLANILLA),0) AS FILAS_JOIN_ACTUAL_ESTIMADAS
FROM R JOIN E ON E.IDENTIDAD = R.DNI;

