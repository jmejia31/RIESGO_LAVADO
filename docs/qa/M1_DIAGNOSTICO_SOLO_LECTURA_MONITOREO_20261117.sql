-- R09 | Grupos naturales con/sin registro en SOCIOS/REPRESENTANTES (regla legado INNER JOIN).
WITH G AS (
    SELECT DISTINCT TRIM(TRANSLATE(DNI, CHR(9)||CHR(10)||CHR(13), '   ')) D FROM DNP_IHSS.REPORTE_COINCIDENCIAS
    WHERE TIPO_CALIFICACION_ID = 1
      AND (TIPO_PERSONA IS NULL OR (UPPER(TRIM(TIPO_PERSONA)) NOT LIKE '%IHSS%' AND UPPER(TRIM(TIPO_PERSONA)) NOT LIKE '%EMPLEAD%'))
      AND UPPER(TRIM(TRANSLATE(DNI, CHR(9)||CHR(10)||CHR(13), '   '))) NOT LIKE 'N/A%'
), S AS (
    SELECT TRIM(TRANSLATE(NUMERO_IDENTIFICACION, CHR(9)||CHR(10)||CHR(13), '   ')) D FROM DNP_IHSS.SOCIOS
    UNION SELECT TRIM(TRANSLATE(NUMERO_IDENTIFICACION, CHR(9)||CHR(10)||CHR(13), '   ')) FROM DNP_IHSS.REPRESENTANTES
)
SELECT SUM(CASE WHEN S.D IS NOT NULL THEN 1 ELSE 0 END) CON_SOCIO_REPRESENTANTE,
       SUM(CASE WHEN S.D IS NULL THEN 1 ELSE 0 END) SIN_SOCIO_REPRESENTANTE
FROM G LEFT JOIN S ON S.D = G.D;

-- R10 | Regla legado completa (V_SOCIOS_REPRESENTANTES INNER JOIN + FECHA_CALIFICO NOT NULL), grupos DNI.
SELECT COUNT(DISTINCT TRIM(TRANSLATE(R.DNI, CHR(9)||CHR(10)||CHR(13), '   '))) GRUPOS_REGLA_LEGADO
FROM DNP_IHSS.REPORTE_COINCIDENCIAS R
WHERE R.TIPO_CALIFICACION_ID = 1 AND R.FECHA_CALIFICO IS NOT NULL
  AND EXISTS (SELECT 1 FROM DNP_IHSS.V_SOCIOS_REPRESENTANTES V
              WHERE V.NUMERO_IDENTIFICACION = R.DNI);

-- R11 | Grupos nuevos no presentes en la regla legado (sin socio/representante exacto o con caracteres de control).
SELECT COUNT(*) GRUPOS_SOLO_REGLA_ACTUAL FROM (
    SELECT DISTINCT TRIM(TRANSLATE(R.DNI, CHR(9)||CHR(10)||CHR(13), '   ')) D FROM DNP_IHSS.REPORTE_COINCIDENCIAS R
    WHERE R.TIPO_CALIFICACION_ID = 1
      AND (R.TIPO_PERSONA IS NULL OR (UPPER(TRIM(R.TIPO_PERSONA)) NOT LIKE '%IHSS%' AND UPPER(TRIM(R.TIPO_PERSONA)) NOT LIKE '%EMPLEAD%'))
      AND UPPER(TRIM(TRANSLATE(R.DNI, CHR(9)||CHR(10)||CHR(13), '   '))) NOT LIKE 'N/A%'
      AND NOT EXISTS (SELECT 1 FROM DNP_IHSS.V_SOCIOS_REPRESENTANTES V WHERE V.NUMERO_IDENTIFICACION = R.DNI)
);

-- R12 | Excluidos por calificacion (no Positivo) entre coincidencias naturales identificadas.
SELECT TIPO_CALIFICACION_ID, COUNT(DISTINCT TRIM(TRANSLATE(DNI, CHR(9)||CHR(10)||CHR(13), '   '))) GRUPOS_DNI
FROM DNP_IHSS.REPORTE_COINCIDENCIAS
WHERE (TIPO_PERSONA IS NULL OR (UPPER(TRIM(TIPO_PERSONA)) NOT LIKE '%IHSS%' AND UPPER(TRIM(TIPO_PERSONA)) NOT LIKE '%EMPLEAD%'))
GROUP BY TIPO_CALIFICACION_ID ORDER BY 1;

