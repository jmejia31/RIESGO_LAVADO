-- R01 | Grupos naturales por clasificacion (conteo que muestra la pestana Naturales identificadas).
WITH R AS (
    SELECT TRIM(TRANSLATE(DNI, CHR(9)||CHR(10)||CHR(13), '   ')) DNI_N
    FROM DNP_IHSS.REPORTE_COINCIDENCIAS
    WHERE TIPO_CALIFICACION_ID = 1
      AND (TIPO_PERSONA IS NULL OR (UPPER(TRIM(TIPO_PERSONA)) NOT LIKE '%IHSS%' AND UPPER(TRIM(TIPO_PERSONA)) NOT LIKE '%EMPLEAD%'))
)
SELECT CASE WHEN DNI_N IS NULL OR UPPER(DNI_N) LIKE 'N/A%'
              OR UPPER(DNI_N) IN ('NULL','VACIO','VACÍO','SIN IDENTIFICACION','SIN IDENTIFICACIÓN')
            THEN 'SIN_IDENTIFICACION' ELSE 'IDENTIFICADA' END CATEGORIA,
       COUNT(*) COINCIDENCIAS, COUNT(DISTINCT DNI_N) GRUPOS_DNI
FROM R GROUP BY CASE WHEN DNI_N IS NULL OR UPPER(DNI_N) LIKE 'N/A%'
              OR UPPER(DNI_N) IN ('NULL','VACIO','VACÍO','SIN IDENTIFICACION','SIN IDENTIFICACIÓN')
            THEN 'SIN_IDENTIFICACION' ELSE 'IDENTIFICADA' END;

-- R02 | Grupos de empleados por clasificacion institucional.
