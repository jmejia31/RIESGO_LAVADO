  WITH CTE_Max_Lote AS (
    SELECT 
        DM.DETALLE_MED_ID,
        DP.NUMERO_LOTES,
        TO_CHAR(DP.FECHA_FABRICACION, 'dd/mm/yyyy') AS FECHA_FABRICACION,
        DP.FECHA_VENCIMIENTO,
        DP.REG_SANITARIO,
        DP.TOTAL_UNIDADES,
        ROW_NUMBER() OVER (
            PARTITION BY DM.DETALLE_MED_ID 
            ORDER BY DP.TOTAL_UNIDADES DESC
        ) AS rn
    FROM 
        CONTROL_ALMACEN.DETALLE_PARTIDA DP
        INNER JOIN CONTROL_ALMACEN.SOLICITUD_ADMINISTRATIVO SA ON DP.SOLI_ADMIN_ID = SA.SOLI_ADMIN_ID
        INNER JOIN CONTROL_ALMACEN.DETALLE_MEDICAMENTO_SOL DM ON DM.DETALLE_MED_ID = SA.DETALLE_MED_ID
)
SELECT 
    DETALLE_MED_ID,
    NUMERO_LOTES,
    FECHA_FABRICACION,
    FECHA_VENCIMIENTO,
    REG_SANITARIO,
    TOTAL_UNIDADES
FROM 
    CTE_Max_Lote
WHERE 
    rn = 1
 
 ;
;

