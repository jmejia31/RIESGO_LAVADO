CREATE OR REPLACE FORCE VIEW "CONTROL_ALMACEN"."VISTALISTASOLIC" ("SOLICITUD_ID", "EMPRESA_PROVEEDOR", "LICITACION", "PO_UNOPS", "USUARIO_ACTUAL_S", "FECHACREO", "ESTADO_DESCRIPCION", "FECHA_SOLICITUD_CITA", "TIPO_COMPRA", "SOLICITUD_FIRMADA", "CITA_ID", "ESTADO", "ESTADO_SOL_ID", "FINALIZADA") AS 
  SELECT DISTINCT
          S.SOLICITUD_ID,
          P.EMPRESA_PROVEEDOR,
          S.LICITACION,
          S.PO_UNOPS,
          S.USUARIO_ACTUAL AS USUARIO_ACTUAL_S,
          TO_CHAR (S.FECHA_CREO, 'DD-MM-YYYY') AS FECHACREO,
          ES.ESTADO_DESCRIPCION AS ESTADO_DESCRIPCION,
          S.FECHA_SOLICITUD_CITA,
          DECODE (S.TIPO_COMPRA,
                  1, 'Compra Directa',
                  2, 'Licitación IHSS',
                  3, 'Licitación UNOPS')
             AS TIPO_COMPRA,
          S.SOLICITUD_FIRMADA,
          C.CITA_ID,
          S.ESTADO,
          ES.ESTADO_SOL_ID, 
          S.FINALIZADA
     FROM SOLICITUD S
          INNER JOIN PROVEEDOR P ON P.CODIGO_PROVEEDOR = S.CODIGO_PROVEEDOR
          LEFT JOIN
          (SELECT SOLICITUD_ID, ESTADO_SOL_ID
             FROM SEGUIMIENTO_SOLICITUD
            WHERE (SOLICITUD_ID, FECHA_CREO) IN (  SELECT SOLICITUD_ID,
                                                          MAX (FECHA_CREO)
                                                     FROM SEGUIMIENTO_SOLICITUD
                                                 GROUP BY SOLICITUD_ID))
          LAST_ESTADO_SS
             ON LAST_ESTADO_SS.SOLICITUD_ID = S.SOLICITUD_ID
          LEFT JOIN SEGUIMIENTO_SOLICITUD SS
             ON     SS.SOLICITUD_ID = S.SOLICITUD_ID
                AND SS.ESTADO_SOL_ID = LAST_ESTADO_SS.ESTADO_SOL_ID
          LEFT JOIN ESTADO_SOLICITUD ES
             ON ES.ESTADO_SOL_ID = SS.ESTADO_SOL_ID
          LEFT JOIN CITA C ON C.SOLICITUD_ID = S.SOLICITUD_ID
 
 ;
;

