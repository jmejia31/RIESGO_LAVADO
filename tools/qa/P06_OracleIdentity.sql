-- P06: execute only from the approved owner/DBA context.
-- This script contains no credentials and performs no DDL or DML.
-- Identity and authentication-persistence checks are intentionally separate.
SELECT
    SYS_CONTEXT('USERENV', 'SESSION_USER') AS SESSION_USER,
    SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AS CURRENT_SCHEMA,
    SYS_CONTEXT('USERENV', 'SERVICE_NAME') AS SERVICE_NAME,
    SYS_CONTEXT('USERENV', 'DB_NAME') AS DB_NAME,
    SYS_CONTEXT('USERENV', 'DB_UNIQUE_NAME') AS DB_UNIQUE_NAME
FROM DUAL;

SELECT
    CASE WHEN (SELECT COUNT(*) FROM USER_TABLES WHERE TABLE_NAME IN ('RL_USUARIOS','RL_REFRESH_TOKENS','RL_AUDITORIA')) = 3 THEN 'AUTH_PERSISTENCE_OWNER=YES' ELSE 'AUTH_PERSISTENCE_OWNER=NO' END,
    CASE WHEN (SELECT COUNT(*) FROM USER_OBJECTS WHERE OBJECT_NAME IN ('RL_USUARIOS','RL_REFRESH_TOKENS','RL_AUDITORIA') AND STATUS <> 'VALID') = 0 THEN 'AUTH_OBJECTS_VALID=YES' ELSE 'AUTH_OBJECTS_VALID=NO' END,
    CASE WHEN (SELECT COUNT(*) FROM USER_TRIGGERS WHERE TABLE_NAME IN ('RL_USUARIOS','RL_REFRESH_TOKENS','RL_AUDITORIA') AND STATUS <> 'ENABLED') = 0 THEN 'AUTH_TRIGGERS_VALID=YES' ELSE 'AUTH_TRIGGERS_VALID=NO' END
FROM DUAL;
